WAITER = """
name: waiter
steps:
  wait:
    select:
      prompt: has the parent answered?
      chooser: agent
      options:
        landed: {description: merged, next: landed}
        nudge: {description: remind the parent, next: nudge-step, interval: 600}
  nudge-step:
    instructions: send one line
    next: wait
  landed:
    instructions: confirm the merge
"""

T0 = datetime(2026, 9, 17, 2, 0, tzinfo=timezone.utc)


