# the layer above it
# --------------------------------------------------------------------------- #
def test_the_remote_variant_inherits_both_edges():
    """``improv-worker-remote`` overrides only ``await-landing``'s title, so
    the new options must reach it unchanged -- a PR that nobody merges is the
    same silence with a different medium."""
    remote = state_mod.load_bundled("improv-worker-remote")
    wait = remote.steps["await-landing"].select
    assert wait.options["nudge"].interval == NUDGE_INTERVAL
    assert wait.options["nudge"].next == "landing-nudge"
    assert wait.options["declined"].next == "landing-declined"
    assert remote.steps["landing-nudge"].next == "await-landing"
    assert remote.steps["rework-gate"].next == "work"
    # The reminder line carries the PR url the remote overlay writes.
    assert "PR url" in _prose(remote.steps["landing-nudge"].instructions)


def test_the_loop_stays_inside_the_engine_s_visit_budget():
    """The backstop is ``max_visits``: past it the run parks in front of a
    person (``waiting_approval``, ``reason: loop_limit``) instead of nudging
    for ever. At ten minutes a pass that is about four hours of silence."""
    for label, wf in _layers():
        assert wf.max_visits == model.DEFAULT_MAX_VISITS, (
            f"{label}: the nudge loop is sized against the default budget; "
            "raising it here would also raise every other loop in the file"
        )


